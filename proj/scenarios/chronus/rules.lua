local function air_route_activity(month, source, destination)
    local activity
    if month < 7 then
        activity = 1
    elseif month < 15 then
        activity = 0.22
    elseif month < 30 then
        activity = 0.58
    elseif month < 34 then
        activity = 0.32
    else
        activity = 0.9
    end
    if source == 137 or destination == 137 then
        if month >= 9 and month < 29 then
            activity = math.min(activity, 0.06)
        elseif month < 33 then
            activity = math.min(activity, 0.48)
        end
    end
    if source == 98 or destination == 98 then
        if month >= 9 and month < 14 then
            activity = math.min(activity, 0.04)
        elseif month < 33 then
            activity = math.min(activity, 0.25)
        end
    end
    if source == 99 or destination == 99 then
        if month >= 9 and month < 14 then
            activity = math.min(activity, 0.08)
        elseif month < 34 then
            activity = math.min(activity, 0.42)
        end
    end
    if month >= 32 and (source == 112 or destination == 112) then return 0 end
    if
        month >= 32
        and source ~= destination
        and (source == 18 or destination == 18)
    then
        activity = math.min(activity, 0.18)
    end
    if
        month >= 52
        and source ~= destination
        and (source == 76 or destination == 76)
    then
        activity = math.min(activity, 0.35)
    end
    activity = math.min(
        activity,
        disaster_air_activity(month, source),
        disaster_air_activity(month, destination),
        conflict_air_activity(month, source),
        conflict_air_activity(month, destination)
    )
    return activity
end

