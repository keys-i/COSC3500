    return month
end

-- Each route gets a stable phase offset and travels back and forth over one leg
local function route_progress(clock, begins, route, speed)
    if clock < begins then return 0 end
    local group = math.floor((route - 1) / 5)
    local slot = (route - 1) % 5
    -- Deterministic route offsets
    local phase = (clock - begins) * speed + (group % 13) * 0.113 + slot * 0.018
    local leg = phase % 2
    if leg > 1 then leg = 2 - leg end
    return leg * 100
end

-- A deterministic wave separates overlapping ships without changing the model
local function ship_wave(month, route, activity)
    return 1
        + 0.85
            * activity
            * (math.sin(month * 1.73 + route * 0.91) + 0.55 * math.sin(
                month * 0.43 + route * 2.17
            ) + 0.25 * math.sin(month * 2.81 + route * 0.29))
            / 1.8
end

-- Monthly compartment update
-- Seed small exposed and infectious populations before the first monthly update
local function initialise()
    for country = 1, COUNTRY_COUNT do
        susceptible[country] = 1
        exposed[country] = 0
        infectious[country] = 0
        recovered[country] = 0
        vaccinated[country] = 0
        deceased[country] = 0
    end
end

-- Advance all compartments from one monthly snapshot into the next snapshot
local function immunisation_rate(country, month)
    local access = math.min(1, 0.15 + vaccine_access[country] / 35)
    local begins = 18 + math.floor(8 * (1 - access))
    if month < begins then return 0 end
    local ramp = math.min(1, (month - begins + 1) / 8)
    return ramp * (0.002 + 0.006 * access)
end

local function transmission_rate(month)
    if month < 7 then return 1.3 end
    if month < 15 then return 1.0 end
    if month < 24 then return 1.4 end
    if month < 32 then return 2.0 end
    if month < 42 then return 0.7 end
    return 0.35
end

local function advance(month)
    if month == 6 then
        local origin = CHINA + 1
        exposed[origin] = 0.0002
        infectious[origin] = 0.00005
        susceptible[origin] = 1 - exposed[origin] - infectious[origin]
    end
    local global_infectious = 0
    for country = 1, COUNTRY_COUNT do
        global_infectious = global_infectious + infectious[country]
    end
    global_infectious = global_infectious / COUNTRY_COUNT

    -- Ping-pong update removes country-order dependence
    local next_s, next_e, next_i = {}, {}, {}
    local next_r, next_v, next_d = {}, {}, {}
    for country = 1, COUNTRY_COUNT do
        local heterogeneity = 0.82 + ((country * 37) % 17) / 50
        local awareness = 1
            / (1 + 18 * infectious[country] + 10 * global_infectious)
        local protection = 1 - 0.65 * vaccinated[country]
        local force = transmission_rate(month)
                * heterogeneity
                * awareness
                * protection
                * infectious[country]
            + 0.18 * global_infectious * protection * air_activity(month)
        local new_exposed =
            math.min(susceptible[country], susceptible[country] * force)
        local progressed = exposed[country] * 0.45
        local resolved = infectious[country] * 0.32
        local fatality = resolved * (0.004 + ((country * 13) % 7) / 10000)
        local immunised = month < 18 and 0
            or math.min(
                susceptible[country] - new_exposed,
                susceptible[country] * immunisation_rate(country, month)
            )

        next_s[country] = susceptible[country] - new_exposed - immunised
        next_e[country] = exposed[country] + new_exposed - progressed
        next_i[country] = infectious[country] + progressed - resolved
        next_r[country] = recovered[country] + resolved - fatality
        next_v[country] = vaccinated[country] + immunised
        next_d[country] = deceased[country] + fatality
    end
    susceptible, exposed, infectious = next_s, next_e, next_i
    recovered, vaccinated, deceased = next_r, next_v, next_d
end

-- Scene publication and host lifecycle
-- Convert country fractions and route activity into the scene's visual fields
local function emit(month)
    local global_active = 0
    for index = 0, COUNTRY_COUNT - 1 do
        local country = index + 1
        global_active = global_active + infectious[country] + exposed[country]
        engine.move(
            index,
            infectious[country] * 100,
            exposed[country] * 100,
            recovered[country] * 100
        )
        engine.move(
            STATE_B_FIRST + index,
            vaccinated[country] * 100,
            deceased[country] * 100,
            susceptible[country] * 100
        )
    end
    global_active = global_active / COUNTRY_COUNT
    for route = 1, #route_sources do
        local source_index = route_sources[route]
        local source = source_index + 1
        local activity = month < route_begins[route] and 0
            or air_route_activity(
                    month,
                    source_index,
                    route_destinations[route]
                )
                * route_frequency[route]
        local affected = activity == 0 and 0
            or math.floor(
                math.min(
                    100,
                    2500 * (infectious[source] + exposed[source]) * activity
                ) + 0.5
            )
        engine.move(
            FLIGHT_FIRST + route - 1,
            route_progress(air_clock(month), route_begins[route], route, 0.16),
            affected,
            activity
        )
    end
    for route = 1, SHIP_COUNT do
        local activity = ship_activity(month, route, ship_begins[route])
        local density = ship_density[route]
        local load = activity == 0 and 0
            or math.min(
                100,
                activity * (12 + 2500 * global_active) * (0.55 + 0.9 * density)
            )
        engine.move(
            SHIP_FIRST + route - 1,
            route_progress(
                ship_clock(month, route),
                ship_begins[route],
                route,
                0.045 + 0.05 * density
            ),
            load,
            ship_wave(month, route, activity)
        )
    end
end

-- Validate table-to-scene alignment before publishing the initial state
function on_setup()
    assert(engine.id("type", "country_state_a") == 0, "country A id")
    assert(engine.id("type", "country_state_b") == 1, "country B id")
    assert(engine.id("type", "flight_state") == 2, "flight id")
    assert(engine.id("type", "ship_state") == 3, "ship id")
    assert(#route_sources == FLIGHT_COUNT, "route sources")
    assert(#route_destinations == FLIGHT_COUNT, "route destinations")
    assert(#route_begins == FLIGHT_COUNT, "route starts")
    assert(#route_frequency == FLIGHT_COUNT, "route frequency")
    assert(#ship_begins == SHIP_COUNT, "ship starts")
    assert(#ship_density == SHIP_COUNT, "ship density")
    initialise()
    assert(air_activity(7) == 0.22 and air_activity(34) == 0.9, "air activity")
    assert(air_route_activity(9, 137, 4) == 0.06, "route restriction")
    assert(air_route_activity(32, 112, 4) == 0, "route closure")
    assert(air_route_activity(7, 147, 4) == 0, "disaster closure")
    assert(air_route_activity(59, 29, 4) == 0.30, "disaster restriction")
    assert(air_route_activity(81, 107, 4) == 0.12, "conflict restriction")
    assert(ship_activity(21, 13, 0) == 0.1, "ship activity")
    assert(ship_activity(81, 9, 0) == 0.08, "Hormuz restriction")
    assert(
        immunisation_rate(CHINA + 1, 18) > 0
            and immunisation_rate(113, 18) == 0
            and immunisation_rate(113, 24) > 0,
        "staggered vaccination"
    )
    assert(transmission_rate(24) > transmission_rate(20), "variant wave")
    assert(
        math.abs(route_progress(12.5, 0, 1, 0.16)) < 0.000001,
        "route progress"
    )
    emit(0)
end

-- The visual month follows the completed compartment update for that month
function on_timeline(month)
    advance(month)
    emit(month)
    if month == 88 then engine.result(0) end
end
