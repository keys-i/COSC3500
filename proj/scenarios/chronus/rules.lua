    if month < 15 then return 7 + (month - 7) * 0.22 end
    if month < 30 then return 8.76 + (month - 15) * 0.58 end
    if month < 34 then return 17.46 + (month - 30) * 0.32 end
    return 18.74 + (month - 34) * 0.9
end

-- A route cannot operate before its source schedule says it exists
local function ship_activity(month, route, begins)
    if month < begins then return 0 end
    if route == 50 or route == 51 then
        if month < 32 then return 1 end
        if month < 38 then return 0.05 end
        if month < 49 then return 0.75 end
        return 0.2
    end
    local suez = route == 13 or route == 52 or route == 53
    if suez and month == 21 then return 0.1 end
    if suez and month >= 54 then return 0.55 end
    return 1
end

local function ship_clock(month, route)
    if route == 50 or route == 51 then
        if month < 32 then return month end
        if month < 38 then return 32 end
        if month < 49 then return 32 + (month - 38) * 0.72 end
        return 39.92 + (month - 49) * 0.18
    end
    if (route == 13 or route == 52 or route == 53) and month >= 54 then
        return 52 + (month - 53) * 0.55
    end
    if (route == 13 or route == 52 or route == 53) and month >= 21 then
        return month - 1
    end
    return month
end

